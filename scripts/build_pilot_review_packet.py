"""Build the human review packet and decision sheet for the 25-task pilot.

Writes, under data/annotations/review_logs/:
  pilot_human_review_packet.md  - per task: EN/BN/BN-CS prompts, units, anchors, task checks
  pilot_human_review_sheet.csv  - one row per decision; each reviewer fills an independent copy

Read-only with respect to prompts and annotations. Re-run after any rubric change.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

from validate_pilot_annotations import ANN, FILES
from validate_prompt_corpus import load_rows

OUT = ANN / "review_logs"
SHEET_FIELDS = ["reviewer_id", "review_date", "task_id", "item", "question", "decision", "proposed_change", "notes"]


def main() -> None:
    prompts = {r["task_id"]: r for r in load_rows()}
    records = [json.loads(line) for f in FILES for line in (ANN / f).read_text(encoding="utf-8").splitlines()]
    md = [
        "# Pilot human review packet",
        "",
        "Generated by `scripts/build_pilot_review_packet.py`; do not edit by hand.",
        "",
        "Two reviewers competent in English and Bengali should each work alone with their own copy of "
        "`pilot_human_review_sheet.csv` and must not see each other's decisions before adjudication "
        "(`ANNOTATION_PROTOCOL.md`). The AI pre-review and AI validation logs in this folder are optional "
        "context; reading them before forming your own judgment may bias you.",
        "",
        "Decision values:",
        "",
        "- `LANG`: `equivalent` / `minor` / `material`",
        "- units and checks: `accept` / `revise` / `reject`",
        "- `RECORD`: `sign-off` / `needs-adjudication`",
        "",
    ]
    rows = []
    for rec in records:
        t, p = rec["task_id"], prompts[rec["task_id"]]
        md += [
            f"## {t} ({rec['domain']}, {rec['difficulty']}, visibility {rec['requirement_visibility']}, "
            f"safety {rec['safety_relevance']})",
            "",
            f"**Objective:** {rec['task_objective']}",
            "",
        ]
        for label, key in (("EN", "prompt_en"), ("BN", "prompt_bn"), ("BN-CS", "prompt_bn_cs")):
            md += [f"**{label}:** {p[key]}", ""]
        md += ["| Unit | Type | Criticality | Mode | Full credit (1) | Partial (0.5) | Rationale |", "|---|---|---|---|---|---|---|"]
        for u in rec["rius"]:
            half = u["scoring_rule"]["0.5"] or "—"
            md.append(
                f"| {u['id']} | {u['riu_type']} | {u['criticality']} | {u['scoring_mode']} | "
                f"{u['description']} | {half} | {u['rationale']} |"
            )
        md.append("")
        for c in rec["task_checks"]:
            md += [f"- **{c['id']} ({c['kind']}):** {c['rule']}"]
        md.append("")
        rows.append({"task_id": t, "item": "LANG", "question": "Are EN, BN and BN-CS semantically equivalent and natural?"})
        rows.append({"task_id": t, "item": "VISIBILITY", "question": f"Is requirement_visibility '{rec['requirement_visibility']}' correct?"})
        rows.append({"task_id": t, "item": "COVERAGE", "question": "Is any required answer element missing, or any unit overlapping or bundled?"})
        for u in rec["rius"]:
            rows.append({"task_id": t, "item": u["id"],
                         "question": f"Required element? Criticality '{u['criticality']}' defensible? Anchors clear for two raters?"})
        for c in rec["task_checks"]:
            rows.append({"task_id": t, "item": c["id"], "question": "Is this check clear and applicable?"})
        rows.append({"task_id": t, "item": "RECORD", "question": "Overall: sign off this record for gold, or send to adjudication?"})
    OUT.mkdir(exist_ok=True)
    (OUT / "pilot_human_review_packet.md").write_text("\n".join(md) + "\n", encoding="utf-8", newline="\n")
    with (OUT / "pilot_human_review_sheet.csv").open("w", encoding="utf-8", newline="") as h:
        w = csv.DictWriter(h, fieldnames=SHEET_FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows({**{k: "" for k in SHEET_FIELDS}, **r} for r in rows)
    print(f"Wrote packet for {len(records)} tasks and {len(rows)} decision rows to {OUT}")


if __name__ == "__main__":
    main()
